let simIntervalo = null;

const sim$ = id => document.getElementById(id);

function simMezclar(array){
  const copia = [...array];
  for(let i=copia.length-1;i>0;i--){
    const j = Math.floor(Math.random()*(i+1));
    [copia[i],copia[j]] = [copia[j],copia[i]];
  }
  return copia;
}

function simSeleccionBalanceada(total){
  const grupos = {};

  preguntasExamen.forEach(q => {
    if(!grupos[q.section]) grupos[q.section] = [];
    grupos[q.section].push(q);
  });

  const secciones = simMezclar(Object.keys(grupos));
  secciones.forEach(s => grupos[s] = simMezclar(grupos[s]));

  const elegidas = [];
  let ronda = 0;

  while(elegidas.length < total){
    let agrego = false;

    for(const seccion of secciones){
      const grupo = grupos[seccion];
      if(grupo[ronda] && elegidas.length < total){
        elegidas.push(grupo[ronda]);
        agrego = true;
      }
    }

    if(!agrego) break;
    ronda++;
  }

  if(elegidas.length < total){
    const usados = new Set(elegidas.map(q => q.n));
    const extras = simMezclar(preguntasExamen.filter(q => !usados.has(q.n)));
    elegidas.push(...extras.slice(0,total-elegidas.length));
  }

  return simMezclar(elegidas).slice(0,total);
}

function simLeerHistorial(){
  try{
    const x = JSON.parse(localStorage.getItem(SIM_CLAVE_HISTORIAL) || "[]");
    return Array.isArray(x) ? x : [];
  }catch(error){
    return [];
  }
}

function simGuardarHistorial(historial){
  localStorage.setItem(SIM_CLAVE_HISTORIAL, JSON.stringify(historial.slice(0,20)));
}

function simGuardarActivo(){
  if(simEstado){
    localStorage.setItem(SIM_CLAVE_ACTIVO, JSON.stringify(simEstado));
  }
}

function simLeerActivo(){
  try{
    const x = JSON.parse(localStorage.getItem(SIM_CLAVE_ACTIVO) || "null");
    if(!x || typeof x !== "object") return null;
    if(!Array.isArray(x.ids) || !x.ids.length) return null;
    if(!x.respuestas || typeof x.respuestas !== "object") x.respuestas = {};
    return x;
  }catch(error){
    return null;
  }
}

function simFormatoNota(n){
  return Number(n).toFixed(1).replace(".", ",");
}

function simFormatoTiempo(segundos){
  const s = Math.max(0, Math.floor(segundos));
  const h = Math.floor(s/3600);
  const m = Math.floor((s%3600)/60);
  const sec = s%60;
  return h > 0
    ? `${String(h).padStart(2,"0")}:${String(m).padStart(2,"0")}:${String(sec).padStart(2,"0")}`
    : `${String(m).padStart(2,"0")}:${String(sec).padStart(2,"0")}`;
}

function simPreguntaPorId(id){
  return preguntasExamen.find(q => Number(q.n) === Number(id));
}

function simMostrarPantalla(nombre){
  sim$("sim-config-section").style.display = nombre === "config" ? "grid" : "none";
  sim$("sim-exam-section").style.display = nombre === "exam" ? "block" : "none";
  sim$("sim-result-section").classList.toggle("visible", nombre === "result");
}

function simActualizarSelector(){
  document.querySelectorAll(".sim-tamano").forEach(btn => {
    const total = Number(btn.dataset.total);
    btn.classList.toggle("activo", total === simTotalSeleccionado);
  });

  const min = SIM_DURACIONES[simTotalSeleccionado];
  sim$("sim-config-tiempo").textContent = `${min} minutos`;
  sim$("sim-start-text").textContent = `Iniciar ${simTotalSeleccionado} preguntas · ${min} min`;
}

function simRenderHistorial(){
  const historial = simLeerHistorial();
  const lista = sim$("sim-history-list");
  const vacio = sim$("sim-history-empty");
  lista.innerHTML = "";

  if(!historial.length){
    vacio.style.display = "block";
    return;
  }

  vacio.style.display = "none";

  historial.slice(0,5).forEach(item => {
    const div = document.createElement("div");
    div.className = "sim-history-item";

    const fecha = document.createElement("strong");
    fecha.textContent = new Date(item.fecha).toLocaleString("es-PE", {dateStyle:"short", timeStyle:"short"});

    const detalle = document.createElement("span");
    detalle.textContent = `${item.total} preguntas · ${item.correctas} correctas · ${item.rendimiento}%`;

    const nota = document.createElement("div");
    nota.className = "nota";
    nota.textContent = `${simFormatoNota(item.nota)}/20`;

    div.append(fecha, detalle, nota);
    lista.appendChild(div);
  });
}

function simIniciarNuevo(){
  const total = simTotalSeleccionado;
  const duracionMin = SIM_DURACIONES[total];
  const seleccion = simSeleccionBalanceada(total);
  const ahora = Date.now();

  simEstado = {
    version:1,
    total,
    duracionMin,
    iniciadoEn:ahora,
    finalizaEn:ahora + duracionMin*60*1000,
    indice:0,
    ids:seleccion.map(q => q.n),
    respuestas:{}
  };

  simGuardarActivo();
  simMostrarPantalla("exam");
  simRenderExamen();
  simIniciarTimer();
  window.scrollTo({top:120, behavior:"smooth"});
}

function simRenderExamen(){
  if(!simEstado) return;

  if(simEstado.indice < 0) simEstado.indice = 0;
  if(simEstado.indice >= simEstado.ids.length) simEstado.indice = simEstado.ids.length - 1;

  const id = simEstado.ids[simEstado.indice];
  const q = simPreguntaPorId(id);
  if(!q) return;

  sim$("sim-exam-title").textContent = `Simulación de ${simEstado.total} preguntas`;
  sim$("sim-question-number").textContent = `Pregunta ${simEstado.indice + 1}`;
  sim$("sim-question-count").textContent = `${simEstado.indice + 1} / ${simEstado.total}`;
  sim$("sim-question-section").textContent = q.section;
  sim$("sim-question-text").textContent = q.pregunta;
  sim$("sim-progress-bar").style.width = `${((simEstado.indice+1)/simEstado.total)*100}%`;

  const opciones = sim$("sim-options");
  opciones.innerHTML = "";
  const elegida = simEstado.respuestas[q.n];

  q.opciones.forEach(op => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "sim-option";
    if(elegida === op.letra) btn.classList.add("seleccionada");

    const letra = document.createElement("span");
    letra.className = "sim-option-letra";
    letra.textContent = op.letra;

    const texto = document.createElement("span");
    texto.textContent = op.texto;

    btn.append(letra, texto);
    btn.addEventListener("click", () => {
      simEstado.respuestas[q.n] = op.letra;
      simGuardarActivo();
      simRenderExamen();
    });

    opciones.appendChild(btn);
  });

  sim$("sim-prev").disabled = simEstado.indice === 0;
  sim$("sim-next").textContent = simEstado.indice === simEstado.total-1 ? "Ir al inicio ↺" : "Siguiente →";

  simRenderPaleta();
  simGuardarActivo();
}

function simRenderPaleta(){
  const paleta = sim$("sim-palette");
  paleta.innerHTML = "";

  simEstado.ids.forEach((id, pos) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "sim-chip";
    btn.textContent = pos + 1;

    if(simEstado.respuestas[id]) btn.classList.add("respondida");
    if(pos === simEstado.indice) btn.classList.add("actual");

    btn.addEventListener("click", () => {
      simEstado.indice = pos;
      simRenderExamen();
      window.scrollTo({top:150, behavior:"smooth"});
    });

    paleta.appendChild(btn);
  });

  const respondidas = Object.keys(simEstado.respuestas).length;
  sim$("sim-answered-count").textContent = `${respondidas} respondidas`;
  sim$("sim-pending-count").textContent = `${simEstado.total-respondidas} pendientes`;
}

function simActualizarTimer(){
  if(!simEstado) return;

  const restantes = Math.max(0, Math.ceil((simEstado.finalizaEn-Date.now())/1000));
  const timer = sim$("sim-timer");
  timer.textContent = simFormatoTiempo(restantes);
  timer.classList.toggle("alerta", restantes <= 600 && restantes > 300);
  timer.classList.toggle("critico", restantes <= 300);

  if(restantes <= 0){
    simFinalizar(true);
  }
}

function simIniciarTimer(){
  clearInterval(simIntervalo);
  simActualizarTimer();
  simIntervalo = setInterval(simActualizarTimer, 1000);
}

function simResumenResultado(){
  let correctas = 0;
  let respondidas = 0;

  simEstado.ids.forEach(id => {
    const q = simPreguntaPorId(id);
    const r = simEstado.respuestas[id];
    if(r){
      respondidas++;
      if(q && r === q.correcta) correctas++;
    }
  });

  const incorrectas = respondidas - correctas;
  const sinResponder = simEstado.total - respondidas;
  const rendimiento = Math.round((correctas/simEstado.total)*100);
  const nota = (correctas/simEstado.total)*20;
  const tiempoTotal = simEstado.duracionMin*60;
  const restantes = Math.max(0, Math.ceil((simEstado.finalizaEn-Date.now())/1000));
  const tiempoUsadoSeg = Math.min(tiempoTotal, Math.max(0, tiempoTotal-restantes));

  return {correctas, respondidas, incorrectas, sinResponder, rendimiento, nota, tiempoUsadoSeg};
}

function simFinalizar(forzado=false){
  if(!simEstado) return;

  if(!forzado){
    const pendientes = simEstado.total - Object.keys(simEstado.respuestas).length;
    const msg = pendientes
      ? `Aún tienes ${pendientes} preguntas sin responder. ¿Finalizar de todos modos?`
      : "¿Finalizar la simulación y calcular tu nota?";
    if(!confirm(msg)) return;
  }

  clearInterval(simIntervalo);

  const resumen = simResumenResultado();
  const registro = {
    id: Date.now(),
    fecha: Date.now(),
    total: simEstado.total,
    duracionMin: simEstado.duracionMin,
    ...resumen
  };

  const historial = simLeerHistorial();
  historial.unshift(registro);
  simGuardarHistorial(historial);

  const ultimo = {
    ...registro,
    ids:[...simEstado.ids],
    respuestas:{...simEstado.respuestas}
  };

  localStorage.setItem(SIM_CLAVE_ULTIMO, JSON.stringify(ultimo));
  localStorage.removeItem(SIM_CLAVE_ACTIVO);

  simRenderResultado(ultimo, forzado);
  simEstado = null;
  simRenderHistorial();
  simMostrarPantalla("result");
  window.scrollTo({top:120, behavior:"smooth"});
}

function simRenderResultado(resultado, porTiempo=false){
  sim$("sim-result-title").textContent = porTiempo ? "Tiempo finalizado" : "Simulación finalizada";
  sim$("sim-result-subtitle").textContent = `${resultado.total} preguntas · ${resultado.duracionMin} minutos asignados`;
  sim$("sim-result-nota").textContent = `${simFormatoNota(resultado.nota)} / 20`;
  sim$("sim-result-correct").textContent = resultado.correctas;
  sim$("sim-result-incorrect").textContent = resultado.incorrectas;
  sim$("sim-result-unanswered").textContent = resultado.sinResponder;
  sim$("sim-result-performance").textContent = `${resultado.rendimiento}%`;
  sim$("sim-result-time").textContent = `Tiempo usado: ${simFormatoTiempo(resultado.tiempoUsadoSeg)}`;

  const lista = sim$("sim-review-list");
  lista.innerHTML = "";
  let errores = 0;

  resultado.ids.forEach((id, pos) => {
    const q = simPreguntaPorId(id);
    if(!q) return;

    const elegida = resultado.respuestas[id];
    if(elegida === q.correcta) return;
    errores++;

    const item = document.createElement("article");
    item.className = "sim-review-item";

    const h4 = document.createElement("h4");
    h4.textContent = `Pregunta ${pos+1} · ${q.pregunta}`;

    const usuario = document.createElement("p");
    usuario.className = "respuesta-usuario";
    const opUsuario = q.opciones.find(o => o.letra === elegida);
    usuario.textContent = elegida
      ? `Tu respuesta: ${elegida}) ${opUsuario ? opUsuario.texto : ""}`
      : "Tu respuesta: sin responder";

    const correcta = document.createElement("p");
    correcta.className = "respuesta-correcta";
    const opCorrecta = q.opciones.find(o => o.letra === q.correcta);
    correcta.textContent = `Correcta: ${q.correcta}) ${opCorrecta ? opCorrecta.texto : ""}`;

    const explicacion = document.createElement("p");
    explicacion.textContent = q.explicacion;

    const fija = document.createElement("div");
    fija.className = "sim-review-fija";
    fija.innerHTML = `<strong>BADBEAR.MED FIJA:</strong> `;
    fija.appendChild(document.createTextNode(q.fija));

    item.append(h4, usuario, correcta, explicacion, fija);
    lista.appendChild(item);
  });

  sim$("sim-review-count").textContent = errores
    ? `${errores} preguntas para revisar`
    : "Sin errores";

  sim$("sim-review-empty").style.display = errores ? "none" : "block";
}

function simReiniciarInterfaz(){
  localStorage.removeItem(SIM_CLAVE_ACTIVO);
  simEstado = null;
  clearInterval(simIntervalo);
  simMostrarPantalla("config");
  simRenderHistorial();
  window.scrollTo({top:120, behavior:"smooth"});
}

function simRestaurarSiExiste(){
  const activo = simLeerActivo();
  if(!activo) return false;

  simEstado = activo;
  simTotalSeleccionado = activo.total || 20;

  if(Date.now() >= simEstado.finalizaEn){
    simFinalizar(true);
    return true;
  }

  simMostrarPantalla("exam");
  simRenderExamen();
  simIniciarTimer();
  return true;
}

document.querySelectorAll(".sim-tamano").forEach(btn => {
  btn.addEventListener("click", () => {
    simTotalSeleccionado = Number(btn.dataset.total) || 20;
    simActualizarSelector();
  });
});

sim$("sim-start").addEventListener("click", simIniciarNuevo);

sim$("sim-prev").addEventListener("click", () => {
  if(!simEstado) return;
  simEstado.indice = Math.max(0, simEstado.indice-1);
  simRenderExamen();
  window.scrollTo({top:150, behavior:"smooth"});
});

sim$("sim-next").addEventListener("click", () => {
  if(!simEstado) return;
  simEstado.indice = simEstado.indice === simEstado.total-1 ? 0 : simEstado.indice+1;
  simRenderExamen();
  window.scrollTo({top:150, behavior:"smooth"});
});

sim$("sim-finish").addEventListener("click", () => simFinalizar(false));
sim$("sim-new").addEventListener("click", simReiniciarInterfaz);

simActualizarSelector();
simRenderHistorial();

if(!simRestaurarSiExiste()){
  simMostrarPantalla("config");
}
